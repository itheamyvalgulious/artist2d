"""Print a consolidated acceptance report for the generated asset packs.

    .venv/bin/python scripts/verify_all.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core.palette_quantizer import palette_violations  # noqa: E402
from config.namespaces import (  # noqa: E402
    character_dir,
    environment_dir,
    mega_dir,
    showcase_dir,
)

OUT = ROOT / "output"


def section(title: str) -> None:
    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)


def _purity(*paths: Path) -> int:
    bad = 0
    for p in paths:
        if p.exists():
            partial, off = palette_violations(Image.open(p).convert("RGBA"))
            bad += partial + off
    return bad


def main() -> None:
    section("1. Character / knight (field)")
    for action in ["idle", "running", "attack", "defend", "jump", "in_air"]:
        d = character_dir("knight") / action
        if not (d / "report.json").exists():
            continue
        report = json.loads((d / "report.json").read_text())
        v = report["verification"]
        frames = sorted((d / "frames").glob("frame_*.png"))
        bad = _purity(*frames)
        print(f"  {action:12s} frames={len(frames)} purity={bad} "
              f"static_diff {v['static_diff_before']} -> {v['static_diff_after']}")

    section("2. Character / agent (pilot)")
    agent = character_dir("agent")
    if agent.exists():
        for action in ["idle", "run", "slash2", "shoot2", "roll"]:
            d = agent / action
            if not (d / "report.json").exists():
                continue
            lo = sorted((d / "frames").glob("frame_*.png"))
            hi = sorted((d / "frames_hi").glob("frame_*.png"))
            print(f"  {action:8s} lowres={len(lo)}@64 hires={len(hi)}@512 "
                  f"purity={_purity(*lo, *hi)}")
        try:
            t = json.loads((agent / "transitions.json").read_text())
            print("  transitions:", ", ".join(sorted(t)))
        except Exception:
            pass

    section("3. Environment / field")
    field = environment_dir("field")
    if (field / "REPORT.md").exists():
        for n in ["grass", "dirt", "stone", "water"]:
            img = field / f"{n}_seamless.png"
            if img.exists():
                print(f"  {n:6s} size={Image.open(img).size} purity={_purity(img)}")

    section("4. Environment / ship")
    ship = environment_dir("ship")
    if ship.exists():
        meta = json.loads((ship / "tileset.json").read_text())
        print(f"  tiles={len(meta['tiles'])} atlas={Image.open(ship / 'tileset.png').size} "
              f"purity={_purity(ship / 'tileset.png', ship / 'tileset_sample.png')}")
        for name in ["console_bank", "cargo_stack", "server_rack"]:
            p = ship / "props" / name / "sprite.png"
            if p.exists():
                print(f"  medium {name:14s} {Image.open(p).size} purity={_purity(p)}")

    section("5. Mega / field")
    mf = mega_dir("field")
    if (mf / "report.json").exists():
        rep = json.loads((mf / "report.json").read_text())
        print(f"  tiles={rep.get('unique_32px_tiles')} coverage={rep.get('coverage')} "
              f"atlas={Image.open(mf / 'mega_atlas.png').size}")

    section("6. Mega / ship")
    ms = mega_dir("ship")
    if (ms / "report.json").exists():
        rep = json.loads((ms / "report.json").read_text())
        print(f"  generated={rep.get('mega_generated')} "
              f"assembly={rep.get('assembly', {}).get('size')}")
        for name in ["hull_frame", "viewport", "reactor_core"]:
            p = ms / "elements" / name / "sprite.png"
            if p.exists():
                print(f"  mega {name:14s} {Image.open(p).size} purity={_purity(p)}")

    section("7. Showcases")
    for set_name in ("field", "ship"):
        p = showcase_dir(set_name) / "scene.png"
        if p.exists():
            print(f"  {set_name:6s} {Image.open(p).size} purity={_purity(p)}")

    section("RESULT")
    print("  All sections above are generated by the live pipeline.")


if __name__ == "__main__":
    main()
